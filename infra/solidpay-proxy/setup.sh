#!/usr/bin/env bash
# One-time bootstrap for the SolidPay egress proxy on a fresh Ubuntu VPS
# (Hetzner). Run as root:
#
#   DOMAIN=pay.pulsenow.xyz bash setup.sh
#
# The app stays on Vercel. This box only relays SolidPay API calls so they leave
# from one fixed IP that SolidPay can whitelist. Self-contained on purpose — it
# can be pasted onto the server without cloning the repo. Idempotent.
set -euo pipefail

DOMAIN="${DOMAIN:?set DOMAIN, e.g. DOMAIN=pay.pulsenow.xyz}"
UPSTREAM="${UPSTREAM:-soliapi.xyz}"
SECRET_FILE="/etc/solidpay-proxy/secret"

if [[ $EUID -ne 0 ]]; then
  echo "Run as root: sudo DOMAIN=$DOMAIN bash setup.sh" >&2
  exit 1
fi

echo "==> Packages"
apt-get update -qq
apt-get install -y -qq curl ca-certificates gpg debian-keyring debian-archive-keyring apt-transport-https ufw openssl

if ! command -v caddy >/dev/null 2>&1; then
  echo "==> Caddy (automatic HTTPS)"
  curl -fsSL https://dl.cloudsmith.io/public/caddy/stable/gpg.key \
    | gpg --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  curl -fsSL https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt \
    | tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
  apt-get update -qq
  apt-get install -y -qq caddy
fi

# Generated once and kept, so re-running the script doesn't silently break the
# value already saved in Vercel.
mkdir -p /etc/solidpay-proxy
if [[ ! -s "$SECRET_FILE" ]]; then
  echo "==> Generating proxy secret"
  openssl rand -hex 32 > "$SECRET_FILE"
fi
chmod 600 "$SECRET_FILE"
SECRET="$(cat "$SECRET_FILE")"

echo "==> Caddy site"
cat > /etc/caddy/Caddyfile <<EOF
# SolidPay egress proxy — generated by infra/solidpay-proxy/setup.sh.
# Anything without the right X-Proxy-Secret gets a 403, so this never becomes an
# open relay from a whitelisted IP.

${DOMAIN} {
	@authorized header X-Proxy-Secret ${SECRET}

	handle @authorized {
		# Never forward our secret to the provider.
		request_header -X-Proxy-Secret

		reverse_proxy https://${UPSTREAM} {
			header_up Host ${UPSTREAM}
			# Strip client-identifying headers — SolidPay should see only this box.
			header_up -X-Forwarded-For
			header_up -X-Real-IP
			transport http {
				read_timeout 60s
			}
		}
	}

	handle {
		respond "Forbidden" 403
	}

	log {
		output file /var/log/caddy/solidpay-proxy.log {
			roll_size 10mb
			roll_keep 5
		}
	}
}
EOF
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null
caddy fmt --overwrite /etc/caddy/Caddyfile
# validate runs as root and creates the log file root-owned; the service runs as
# the caddy user and would then die with "permission denied" on startup.
mkdir -p /var/log/caddy
chown -R caddy:caddy /var/log/caddy
systemctl enable caddy >/dev/null
# Restart, not reload: on a fresh install reload fails noisily before Caddy has
# fully come up, even though the config is fine.
systemctl restart caddy

echo "==> Firewall"
ufw allow OpenSSH >/dev/null
ufw allow 80/tcp  >/dev/null   # Let's Encrypt HTTP challenge
ufw allow 443/tcp >/dev/null
ufw --force enable >/dev/null

IPV4="$(curl -4 -fsS https://api.ipify.org || echo 'none')"
IPV6="$(curl -6 -fsS https://api6.ipify.org || echo 'none')"

cat <<EOF

Done.

Send BOTH addresses to SolidPay to whitelist (payIn + payOut):
  IPv4: ${IPV4}
  IPv6: ${IPV6}

Set these in Vercel -> Project -> Settings -> Environment Variables (Production), then redeploy:
  SOLID_PAY_BASE_URL=https://${DOMAIN}
  SOLID_PAY_PROXY_SECRET=${SECRET}

DNS: an A record for ${DOMAIN} -> ${IPV4} (and AAAA -> ${IPV6}) must exist
before Caddy can issue the certificate.
EOF
